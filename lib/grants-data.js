// DUPLICATE ID VALIDATION - Security Check
// ============================================
// This runs when the module is loaded and will throw an error
// if any duplicate grant IDs are found (including rejected grants)

function validateGrantIds() {
  const idCounts = {}
  const duplicates = []

  for (const grant of grants) {
    if (!grant.id) {
      console.error('Grant missing ID:', grant.name)
      continue
    }

    if (idCounts[grant.id]) {
      duplicates.push({
        id: grant.id,
        firstGrant: idCounts[grant.id].name,
        secondGrant: grant.name
      })
    } else {
      idCounts[grant.id] = grant
    }
  }

  if (duplicates.length > 0) {
    const errorLines = duplicates.map(function(d) {
      return '  - "' + d.id + '" appears in: ' + d.firstGrant + ', ' + d.secondGrant
    })

    throw new Error(
      '\nDUPLICATE GRANT IDs DETECTED!\n' +
      'The following grants have duplicate IDs:\n' +
      errorLines.join('\n') + '\n\n' +
      'Each grant must have a unique ID. Please fix this before deploying.'
    )
  }

  // Also check for missing required fields
  const requiredFields = ['id', 'name', 'region', 'category']
  for (const grant of grants) {
    for (const field of requiredFields) {
      if (!grant[field]) {
        console.warn('Grant "' + (grant.name || grant.id) + '" missing required field: ' + field)
      }
    }
  }

  if (typeof window === 'undefined') {
    // Only log in server/build context
    console.log('Grant validation passed: ' + grants.length + ' grants, all IDs unique')
  }
}

// Run validation on module load
validateGrantIds()

